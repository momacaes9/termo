def selecionar_modo():
    modo = input("Selecione o modo (Turbo ou Eco): ")
    while modo != "Turbo" and modo != "Eco":
        print("Inválido! Digite Turbo ou Eco.")
        modo = input("Selecione o modo (Turbo ou Eco): ")
    return modo


def selecionar_capacidade():
    capacidade = input("Selecione a capacidade industrial (P = Pequena / G = Grande): ")
    while capacidade != "P" and capacidade != "G":
        print("Inválido! Digite P ou G.")
        capacidade = input("Selecione a capacidade industrial (P = Pequena / G = Grande): ")
    return capacidade


def obter_valores_base():
    forca = float(input("Digite a força base (N): "))
    rotacoes = float(input("Digite as rotações base (RPM): "))
    return forca, rotacoes


def aplicar_modificadores(forca, rotacoes, modo, capacidade):
    # Modo Eco reduz rotações em 50%
    if modo == "Eco":
        rotacoes *= 0.50

    # Capacidade Pequena reduz força em 50%
    if capacidade == "P":
        forca *= 0.50

    return forca, rotacoes


def calcular_potencia(forca, rotacoes):
    return forca * rotacoes


def maquina_padrao():
    forca_base, rotacoes_base = obter_valores_base()
    modo = selecionar_modo()
    capacidade = selecionar_capacidade()

    forca, rotacoes = aplicar_modificadores(forca_base, rotacoes_base, modo, capacidade)
    potencia = calcular_potencia(forca, rotacoes)

    print(f"\n--- Resultado ---")
    print(f"Força aplicada:   {forca:.2f} N")
    print(f"Rotações:         {rotacoes:.2f} RPM")
    print(f"Potência gerada:  {potencia:.2f} W")

